/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_USART1_UART_Init();
  MX_TIM8_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM5_Init();
  MX_TIM7_Init();
  MX_ADC1_Init();
  MX_I2C2_Init();
  MX_SPI2_Init();
  /* USER CODE BEGIN 2 */
  Key_Init();
  Servo_Init();                     /* TIM8_CH3 / PC8，上电回中位 1500 µs */
  Motor_Init();                     /* TIM1 CH1~CH4，上电确保电机停转 */
  Encoder_Init();                   /* TIM2/TIM5 编码器接口，清零计数 */
  SpeedLoop_Init();                 /* 双轮 PID + 启动 TIM7 10 ms 中断 */
  Voltage_Init();                   /* ADC1 三通道：PB0 / VREFINT / 温度，启动 DMA */
  OLED_Init();                      /* U8g2 / SSD1306 128x64，SPI2（8 孔 DISPLAY 座）*/

  /* QMI8658：上电保持静止约 0.6 s 做陀螺零偏 */
  uint8_t imu_ok = IMU_Init();
  if (imu_ok == 0) {
      IMU_CalibrateGyro(1000);      /* 约 2 s，带静止检测 */
  }

  printf("\r\n=== TARS-Robot MCU boot ===\r\n");
  printf("SYSCLK = %lu Hz\r\n", (unsigned long)SystemCoreClock);
  printf("printf redirect to USART1 @115200 OK\r\n");
  printf("KEY1: click / long press\r\n");
  printf("servo init: %u us (50 Hz, 1 us/count)\r\n", Servo_GetPulseUs());
  printf("motor init: L=%d R=%d\r\n",
         Motor_GetPulse(MOTOR_LEFT), Motor_GetPulse(MOTOR_RIGHT));
  printf("motor switch = %u (PD3, active level %d)\r\n",
         Motor_IsSwitchOn(), (int)MOTOR_SW_ON_LEVEL);
  printf("encoder init: L raw=%lu R raw=%lu\r\n",
         (unsigned long)Encoder_GetRaw(ENC_LEFT),
         (unsigned long)Encoder_GetRaw(ENC_RIGHT));
  printf("IMU: %s (ID=0x%02X)\r\n",
         (imu_ok == 0) ? "OK" :
         (imu_ok == 1) ? "NOT FOUND" :
         (imu_ok == 2) ? "WHO_AM_I BAD" : "CTRL WRITE FAIL",
         IMU_GetWhoAmI());
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    uint32_t now = HAL_GetTick();

    /* 按键：单击切换“停/前进”，长按急停 */
    static uint32_t t_key = 0;
    static float    target_mps = 0.0f;
    if (now - t_key >= 10U) {
        t_key = now;
        Key_Task();

        switch (Key_GetEvent()) {
        case KEY_EVENT_CLICK:
            target_mps = (target_mps > 0.0f) ? 0.0f : 0.15f;
            SpeedLoop_SetTargetMps(target_mps, target_mps);
            printf("target = %.2f m/s\r\n", target_mps);
            break;

        case KEY_EVENT_LONG_PRESS:
            target_mps = 0.0f;
            SpeedLoop_Stop();
            printf("EMERGENCY STOP\r\n");
            break;

        default:
            break;
        }
    }

    /* IMU：10 ms 更新一次（Fusion AHRS，I2C2） */
    static uint32_t t_imu = 0;
    if (now - t_imu >= 10U) {
        t_imu = now;
        IMU_Update(0.01f);
    }

    /* 电压：100 ms 采样一次；严重低压立即停车 */
    static uint32_t t_vbat = 0;
    if (now - t_vbat >= 100U) {
        t_vbat = now;
        Voltage_Task();
        if (Voltage_IsCritical()) {
            SpeedLoop_Stop();
        }
    }

    /* 心跳：本地演示保活。
     * SpeedLoop 有“300 ms 无心跳自动停车”保护，本地没有上位机，
     * 所以这里每 100 ms 喂一次。第 9 章接协议后改由协议层喂。 */
    static uint32_t t_hb = 0;
    if (now - t_hb >= 100U) {
        t_hb = now;
        SpeedLoop_Heartbeat();
    }

    /* 500 ms 打印实际速度。
     * 注意：这里绝不能调用 Encoder_ReadDelta —— 它会把 TIM7 中断里的
     * 增量“偷走”，导致速度环反馈丢失。要用 SpeedLoop 保存好的值。 */
    static uint32_t t_log = 0;
    if (now - t_log >= 500U) {
        t_log = now;
        float vl = 0.0f, vr = 0.0f;
        SpeedLoop_GetActualMps(&vl, &vr);
        float ax, ay, az;
        IMU_GetAcc(&ax, &ay, &az);
        printf("IMU a=%.2f/%.2f/%.2f r=%6.1f p=%6.1f y=%6.1f | BAT %.2fV err=%lu\r\n",
               ax, ay, az,
               IMU_GetRoll(), IMU_GetPitch(), IMU_GetYaw(),
               Voltage_Get(), (unsigned long)IMU_GetErrorCount());
    }

    /* OLED 仪表盘：200 ms 刷新，不进 10 ms 控制环 */
    static uint32_t t_oled = 0;
    if (now - t_oled >= 200U) {
        t_oled = now;
        OLED_Dashboard();
    }
  }
  /* USER CODE END 3 */
}

